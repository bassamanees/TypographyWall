def interaction_box(sensitivity):
    """منطقة التفاعل لحساسية معيّنة (1 = الصورة كلها تقريباً، 2 = نصفها الأوسط)."""
    s = min(max(sensitivity, HAND_SENSITIVITY_RANGE[0]), HAND_SENSITIVITY_RANGE[1])
    half = 0.46 / s
    cx, cy = INTERACTION_CENTER
    return (cx - half, max(0.0, cy - half * 0.95), cx + half, min(1.0, cy + half * 0.95))


